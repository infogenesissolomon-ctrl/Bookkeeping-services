-- Email notifications for new inquiries, and replies sent to clients from /admin/.
-- Both are written only by the Vercel functions with the server-only secret key. Admins can read them; nobody else can.

-- Notification state for each inquiry. /api/inquiries sets 'sending' (or 'not_configured') when the row is saved,
-- then 'sent' or 'failed'. An admin can retry 'failed', 'not_configured', and 'sending' rows that never finished.
alter table public.inquiries
  add column if not exists notification_status text not null default 'not_configured'
    check (notification_status in ('not_configured', 'sending', 'sent', 'failed')),
  add column if not exists notification_attempts integer not null default 0 check (notification_attempts >= 0),
  add column if not exists notification_attempted_at timestamptz,
  add column if not exists notification_sent_at timestamptz,
  add column if not exists notification_error text check (notification_error is null or char_length(notification_error) <= 300);

grant select (notification_status, notification_attempts, notification_attempted_at, notification_sent_at, notification_error)
  on public.inquiries to authenticated;

-- Replies sent from the dashboard. One row per send attempt, so failed attempts stay visible in the history.
create table if not exists public.inquiry_replies (
  id uuid primary key default gen_random_uuid(),
  inquiry_id uuid not null references public.inquiries (id) on delete cascade,
  -- Random id generated by the dashboard for one click of Send Reply, so a retried request is not sent twice.
  client_ref uuid not null unique,
  recipient_email text not null check (char_length(recipient_email) <= 254),
  subject text not null check (char_length(btrim(subject)) between 1 and 200),
  reply_body text not null check (char_length(btrim(reply_body)) between 1 and 10000),
  send_status text not null default 'sending' check (send_status in ('sending', 'sent', 'failed')),
  provider_message_id text check (provider_message_id is null or char_length(provider_message_id) <= 300),
  error text check (error is null or char_length(error) <= 300),
  sent_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  sent_at timestamptz
);

create index if not exists inquiry_replies_inquiry_created_idx on public.inquiry_replies (inquiry_id, created_at desc);

alter table public.inquiry_replies enable row level security;
revoke all on public.inquiry_replies from anon, authenticated;
grant select (id, inquiry_id, recipient_email, subject, reply_body, send_status, provider_message_id, error, created_at, sent_at)
  on public.inquiry_replies to authenticated;

drop policy if exists "Admins can read replies" on public.inquiry_replies;
create policy "Admins can read replies" on public.inquiry_replies
  for select to authenticated
  using ((select public.is_admin()));
