-- Contact inquiries for the Genesis Solomon bookkeeping website.
-- Public visitors never touch this table directly: the Vercel function /api/inquiries inserts rows with the
-- server-only secret key. Signed-in admins (listed in public.admin_users) can read, update status, and delete.

create table if not exists public.inquiries (
  id uuid primary key default gen_random_uuid(),
  full_name text not null check (char_length(btrim(full_name)) between 1 and 100),
  email text not null check (char_length(email) <= 254 and email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  business_name text check (business_name is null or char_length(business_name) <= 120),
  service_needed text not null check (service_needed in (
    'Bookkeeping Services',
    'Administrative Support',
    'Both Bookkeeping and Administrative Support',
    'Other'
  )),
  industry text not null check (industry in (
    'Construction',
    'Real Estate',
    'Small Business',
    'Landscaping & Lawn Care',
    'Other'
  )),
  message text not null check (char_length(btrim(message)) between 1 and 3000),
  status text not null default 'new' check (status in ('new', 'in_progress', 'replied', 'closed')),
  -- Random id generated by the visitor's browser for one submission, so a retried request is not saved twice.
  client_ref uuid unique,
  -- HMAC of the submitter's IP address, used only for rate limiting. The raw IP is never stored.
  submitter_hash text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists inquiries_created_at_idx on public.inquiries (created_at desc);
create index if not exists inquiries_status_created_at_idx on public.inquiries (status, created_at desc);
create index if not exists inquiries_submitter_recent_idx on public.inquiries (submitter_hash, created_at desc);

-- Accounts allowed into /admin/. Rows are added by hand in the SQL editor (see docs/INQUIRY-SYSTEM-SETUP.md).
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists inquiries_set_updated_at on public.inquiries;
create trigger inquiries_set_updated_at
  before update on public.inquiries
  for each row execute function public.set_updated_at();

-- Row level security: with no policy for anon, public visitors can neither read nor write.
alter table public.inquiries enable row level security;
alter table public.admin_users enable row level security;

-- Table privileges. Supabase grants new tables to anon/authenticated by default, so start from nothing.
revoke all on public.inquiries from anon, authenticated;
revoke all on public.admin_users from anon, authenticated;

-- Admins may read every column except the rate-limit hash, change only the status, and delete.
grant select (id, full_name, email, business_name, service_needed, industry, message, status, created_at, updated_at)
  on public.inquiries to authenticated;
grant update (status) on public.inquiries to authenticated;
grant delete on public.inquiries to authenticated;

drop policy if exists "Admins can read inquiries" on public.inquiries;
create policy "Admins can read inquiries" on public.inquiries
  for select to authenticated
  using ((select public.is_admin()));

drop policy if exists "Admins can update inquiry status" on public.inquiries;
create policy "Admins can update inquiry status" on public.inquiries
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists "Admins can delete inquiries" on public.inquiries;
create policy "Admins can delete inquiries" on public.inquiries
  for delete to authenticated
  using ((select public.is_admin()));

-- admin_users has no policies on purpose: only is_admin() (security definer) and the SQL editor read it.
